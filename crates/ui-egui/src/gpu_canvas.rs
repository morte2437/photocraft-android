//! GPU document canvas: an `egui_wgpu` paint callback that draws one document view with a custom
//! WGSL shader.
//!
//! The document's composite lives on the GPU as one or more mipmapped textures (premultiplied
//! alpha, sRGB-encoded values, matching how the CPU path and egui blend): `Rgba8Unorm` for 8-bit
//! documents, `Rgba16Float` for 16- and 32-bit documents when the adapter can render to and
//! filter it (so smooth gradients don't band and 32-bit values above 1.0 survive for the 32-bit
//! preview), within [`F16_BUDGET_PX`]; larger high-bit documents fall back to `Rgba8Unorm`.
//! Uploads are either full (new document, size change, re-render) or a damage rect (brush
//! strokes); after an upload only the affected region of each mip level is regenerated by a
//! render-pass blit chain. Documents larger than the device's maximum texture size are split
//! into tiles.
//!
//! Per frame the shader draws, in *device pixels*:
//! - a soft analytic drop shadow around the document on the pasteboard (erf-blurred box),
//! - a transparency checkerboard (8 pt squares, grays 255/204, the same size at every zoom)
//!   under the document, anchored to the document's top-left corner so it moves with the image,
//! - the document itself, sampled trilinearly when zoomed out, bilinearly between 1× and 2×, and
//!   with an anti-aliased "sharp nearest" filter at integer scales and ≥ 2×,
//! - a one-device-pixel pixel grid above 500% zoom, over pixels with content only.
//!
//! GPU resources live in the renderer's `callback_resources` type map; the per-frame callback only
//! carries plain view parameters, so it is `Send + Sync` on every target (including wasm).
//!
//! The document pixels still come from the CPU compositor (`photocraft-compose`) for now; the wgpu
//! compositor (M5) will render straight into these tiles.

use std::collections::HashMap;
use std::num::NonZeroU64;
use std::sync::atomic::Ordering;

use eframe::egui_wgpu::{self, CallbackResources, CallbackTrait, RenderState, ScreenDescriptor};
use eframe::wgpu;

pub use photocraft_gpu::{DeviceHealth, Fault};

/// Default tile side; documents up to this size (and the device limit) use a single texture.
pub const DEFAULT_TILE: u32 = 8192;
/// Mip levels no larger than this on either side are redrawn whole on every edit rather than
/// just their damage (see [`mip_damage`], #6418). Every corrupted level measured was at most
/// 64 px; this leaves a factor of two.
const WHOLE_MIP_SIDE: u32 = 128;
const FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba8Unorm;
/// Canvas texture format of high-bit documents (see [`GpuCanvas::format_for`]).
const FORMAT_HIGH: wgpu::TextureFormat = wgpu::TextureFormat::Rgba16Float;
/// Largest high-bit document (in pixels) given an `Rgba16Float` canvas texture: 100 MP is
/// 800 MB at level 0, about 1.07 GB with mips (twice the `Rgba8Unorm` cost). Bigger 16/32-bit
/// documents (a 14000² one would need 2.1 GB) use `Rgba8Unorm`, so they stay on the GPU like
/// 8-bit ones. `PHOTOCRAFT_CANVAS_F16=0` turns the float canvas off, `=1` ignores this budget.
pub const F16_BUDGET_PX: u64 = 100_000_000;
const VIEW_UNIFORM_SIZE: u64 = 128;
const VIEW_FLOATS: usize = 32;
const TILE_UNIFORM_SIZE: u64 = 16;

/// Whether this view can use the GPU canvas. Flip and non-square pixel aspect correction are
/// still CPU blits (the shader's filtering assumes square pixels); rotation is a shader uniform.
pub fn gpu_view_ok(flip: bool, _rotation: f32, aspect: f32) -> bool {
    !flip && (aspect - 1.0).abs() < 1e-6
}

/// Parameters for drawing one document view. Positions are in egui points.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ViewParams {
    /// Document key used with [`GpuCanvas::upload_full`].
    pub doc: u64,
    /// Document size in pixels.
    pub doc_size: [u32; 2],
    /// Screen points per document pixel.
    pub zoom: f32,
    /// Document point shown at the centre of the canvas rect.
    pub center: [f32; 2],
    /// Camera rotation in radians, clockwise in Y-down screen space. Rotate around [`Self::center`]
    /// before sampling. Flip stays on the CPU path.
    pub rotation: f32,
    /// Draw the drop shadow on the pasteboard.
    pub shadow: bool,
    /// Draw the pixel grid at high zoom.
    pub pixel_grid: bool,
    /// Distinguishes views painted in the same frame (main canvas, extra windows).
    pub view_key: u64,
    /// Display transform: 0 none, 1 the document's display LUT (document → monitor profile,
    /// Proof Colors), 2 LUT plus the gamut warning, 3 matrix/shaper (see [`GpuCanvas::set_display_lut`]).
    pub display: u8,
    /// The display the view is on (its LUT is per document and display, #569; 0 = unknown).
    pub output: u32,
    /// View › 32-bit Preview Options (exposure in stops, gamma), applied to the texture values
    /// before the display LUT; `None` when off. The display LUT must then leave it out
    /// (`ColorState::gpu_canvas_lut`).
    pub hdr: Option<[f32; 2]>,
    /// Where this draw puts the document, in document pixels from its own place: `[0, 0]` for the
    /// document, a whole number of widths and heights for a View › Pattern Preview copy (#1067).
    /// A copy samples the same texture, so nothing is composited again.
    pub offset: [f32; 2],
}

/// When high-bit documents get an `Rgba16Float` canvas texture.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum HighPolicy {
    /// The adapter can't render to or filter `Rgba16Float`, or `PHOTOCRAFT_CANVAS_F16=0`.
    Off,
    /// Up to [`F16_BUDGET_PX`].
    Budget,
    /// Always (`PHOTOCRAFT_CANVAS_F16=1`).
    Always,
}

/// Uploads documents to the GPU and paints them. Cheap to clone.
///
/// Once the device is lost or reports an uncaptured error (see [`GpuCanvas::fault`]), every
/// method is a no-op or an `Err`, so nothing reaches the GPU again; the app then switches to the
/// CPU canvas (#243).
#[derive(Clone)]
pub struct GpuCanvas {
    rs: RenderState,
    tile: u32,
    high: HighPolicy,
    health: photocraft_gpu::DeviceHealth,
    /// [`video_memory`] of the adapter, detected once.
    vram: Option<u64>,
    /// [`canvas_budget`], shared with the paint callback's resources: [`GpuCanvas::format_for`]
    /// reads it while the renderer is locked.
    canvas_budget: std::sync::Arc<std::sync::atomic::AtomicU64>,
}

/// Whether `regenerate_mips` builds each level in a scratch texture and copies it back: on
/// Intel adapters under DX12 only, where some drivers corrupt reduced previews when a pass
/// samples one mip level and renders into another of the same texture (#892, Intel UHD 620).
/// Everywhere else it renders straight into the level: on an NVIDIA DX12 adapter the scratch
/// textures, created per level on every refresh, cost about 1 ms of CPU time per brush dab
/// (#4515). `PHOTOCRAFT_SEPARATE_MIPS` (`setting`) forces it on (`1`) or off (`0`).
pub fn separate_mip_targets(backend: wgpu::Backend, vendor: u32, setting: Option<&str>) -> bool {
    const INTEL: u32 = 0x8086;
    match setting.map(str::trim) {
        Some("1") => true,
        Some("0") => false,
        _ => backend == wgpu::Backend::Dx12 && vendor == INTEL,
    }
}

/// Can `adapter` use `Rgba16Float` as a sampled, filtered, render-target and copy texture?
/// (Core WebGPU guarantees it; WebGL2 needs `EXT_color_buffer_float`, and some drivers lack it.)
pub fn supports_f16_canvas(adapter: &wgpu::Adapter) -> bool {
    let f = adapter.get_texture_format_features(FORMAT_HIGH);
    let usages = wgpu::TextureUsages::TEXTURE_BINDING | wgpu::TextureUsages::RENDER_ATTACHMENT | wgpu::TextureUsages::COPY_DST | wgpu::TextureUsages::COPY_SRC;
    f.allowed_usages.contains(usages) && f.flags.contains(wgpu::TextureFormatFeatureFlags::FILTERABLE)
}

impl GpuCanvas {
    /// Create pipelines and register resources with the egui renderer.
    pub fn new(rs: &RenderState) -> Self {
        Self::with_tile(rs, None)
    }

    /// Like [`GpuCanvas::new`] with a preferred texture tile side (`PHOTOCRAFT_GPU_TILE` wins).
    pub fn with_tile(rs: &RenderState, tile: Option<u32>) -> Self {
        let max = rs.device.limits().max_texture_dimension_2d;
        let env_tile = std::env::var("PHOTOCRAFT_GPU_TILE").ok().and_then(|v| v.parse::<u32>().ok());
        let tile = env_tile.or(tile).unwrap_or(DEFAULT_TILE).clamp(64, max);
        let high = match std::env::var("PHOTOCRAFT_CANVAS_F16").ok().as_deref() {
            _ if !supports_f16_canvas(&rs.adapter) => HighPolicy::Off,
            Some("0") => HighPolicy::Off,
            Some("1") => HighPolicy::Always,
            _ => HighPolicy::Budget,
        };
        // Device loss and uncaptured errors mark this flag instead of panicking (#243).
        let health = photocraft_gpu::DeviceHealth::watch(&rs.device);
        let mut res = Resources::new(&rs.device, &rs.queue, rs.target_format, high != HighPolicy::Off);
        res.health = health.clone();
        let info = rs.adapter.get_info();
        res.separate_mip_targets = separate_mip_targets(info.backend, info.vendor, std::env::var("PHOTOCRAFT_SEPARATE_MIPS").ok().as_deref());
        let vram = video_memory(&info);
        res.canvas_budget.store(canvas_budget(physical_memory(), vram), Ordering::Relaxed);
        let budget = res.canvas_budget.clone();
        rs.renderer.write().callback_resources.insert(res);
        log::info!(
            "gpu canvas: target {:?}, max texture {max}, tile {tile}, 16F canvas {high:?}, video memory {}",
            rs.target_format,
            vram.map_or_else(|| "unknown".to_owned(), |b| format!("{} MB", b >> 20))
        );
        Self { rs: rs.clone(), tile, high, health, vram, canvas_budget: budget }
    }

    /// The device's health flag (shared with the wgpu compositor and the paint callback).
    pub fn health(&self) -> &photocraft_gpu::DeviceHealth {
        &self.health
    }

    /// Why the GPU can't be used any more (`None` while it can).
    pub fn fault(&self) -> Option<photocraft_gpu::Fault> {
        self.health.fault()
    }

    /// Free every GPU resource the canvas holds (compositor pages, document textures, LUTs) after
    /// a fault; the paint callback draws nothing from then on.
    pub fn release(&self) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<Resources>() {
            res.compositor = None;
            res.compositor_failed = Some(photocraft_gpu::Unsupported(self.fault().map_or_else(|| "GPU canvas released".into(), |f| f.to_string())));
            res.docs.clear();
            res.luts.clear();
            res.display_lut_signatures.clear();
            res.views.clear();
        }
    }

    /// The adapter this canvas renders with.
    pub fn adapter_info(&self) -> wgpu::AdapterInfo {
        self.rs.adapter.get_info()
    }

    /// The adapter's own memory where it has one and the platform reports it (see
    /// [`video_memory`]); it caps [`memory_budget`] and [`canvas_budget`].
    pub fn video_memory(&self) -> Option<u64> {
        self.vram
    }

    /// The canvas texture format for a document of `depth` and `size`: `Rgba16Float` for 16/32-bit
    /// documents when the adapter supports it and the document fits [`F16_BUDGET_PX`], else
    /// `Rgba8Unorm`.
    /// The device's largest 2D texture side (egui textures can use it too).
    pub fn max_texture_side(&self) -> usize {
        self.rs.device.limits().max_texture_dimension_2d as usize
    }

    pub fn format_for(&self, depth: photocraft_doc::SampleType, size: [u32; 2]) -> wgpu::TextureFormat {
        let px = size[0] as u64 * size[1] as u64;
        let high = match self.high {
            HighPolicy::Off => false,
            // Within the canvas budget too: a 16-bit canvas a small card can't hold as floats
            // stays on the GPU as `Rgba8Unorm` rather than falling back to the CPU canvas.
            HighPolicy::Budget => {
                px <= F16_BUDGET_PX && canvas_texture_bytes(size, self.tile, texel_bytes(FORMAT_HIGH)) <= self.canvas_budget.load(Ordering::Relaxed)
            }
            HighPolicy::Always => true,
        };
        if high && depth != photocraft_doc::SampleType::U8 { FORMAT_HIGH } else { FORMAT }
    }

    /// Format and GPU bytes (all tiles, all mip levels) of document `key`'s canvas texture.
    pub fn texture_info(&self, key: u64) -> Option<(wgpu::TextureFormat, u64)> {
        let r = self.rs.renderer.read();
        let d = r.callback_resources.get::<Resources>()?.docs.get(&key)?;
        let bpp = texel_bytes(d.format);
        let bytes = d
            .tiles
            .iter()
            .map(|t| (0..t.levels.len() as u32).map(|l| ((t.rect[2] >> l).max(1) as u64) * ((t.rect[3] >> l).max(1) as u64) * bpp).sum::<u64>())
            .sum();
        Some((d.format, bytes))
    }

    /// Set the GPU memory the wgpu compositor may hold for layer pages and caches (see
    /// [`memory_budget`]); pages beyond it are evicted least recently used first.
    pub fn set_memory_budget(&self, bytes: u64) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<Resources>() {
            res.compositor_budget = Some(bytes);
        }
    }

    /// The compositor's memory budget (`None` until [`GpuCanvas::set_memory_budget`]).
    pub fn memory_budget(&self) -> Option<u64> {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<Resources>()?.compositor_budget
    }

    /// Set the GPU bytes one document's display texture set may take (see [`canvas_budget`]).
    pub fn set_canvas_budget(&self, bytes: u64) {
        self.canvas_budget.store(bytes, Ordering::Relaxed);
    }

    /// Whether `doc`'s display textures fit [`canvas_budget`]; when they don't, nothing is
    /// created for it and it is drawn on the CPU canvas.
    pub fn fits_canvas(&self, doc: &photocraft_doc::Document) -> bool {
        let size = [doc.size.width, doc.size.height];
        let bytes = canvas_texture_bytes(size, self.tile, texel_bytes(self.format_for(doc.depth, size)));
        let r = self.rs.renderer.read();
        r.callback_resources.get::<Resources>().is_some_and(|res| bytes <= res.canvas_budget.load(Ordering::Relaxed))
    }

    /// Cap lower-stack composite reuse; zero disables it for profiling the uncached path.
    pub fn set_composite_cache_budget(&self, bytes: u64) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<Resources>() {
            res.compositor_cache_budget = Some(bytes);
            if let Some(comp) = &mut res.compositor {
                comp.set_composite_cache_budget(bytes);
            }
        }
    }

    /// The document area the view shows: full refreshes composite it last, so its layer pages
    /// are the ones still resident for the edits that follow.
    pub fn set_focus(&self, focus: Option<photocraft_geom::Rect>) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<Resources>() {
            res.compositor_focus = focus;
        }
    }

    /// Take any GPU measurement that has landed since the last call, without compositing
    /// anything. [`Compositor::render`] carries measurements out in its stats, but a refresh is
    /// the only thing that collects them, so the last refresh before the app goes idle would
    /// never be reported. The frame loop calls this so it is.
    pub fn take_gpu_timing(&self) -> Option<photocraft_gpu::GpuTiming> {
        let mut r = self.rs.renderer.write();
        r.callback_resources.get_mut::<Resources>()?.compositor.as_mut()?.take_gpu_timing()
    }

    /// GPU bytes the wgpu compositor holds: resident layer pages and caches (effect maps and
    /// lower-stack chunks). Keep the scorecard's memory measurements inclusive of reuse.
    pub fn compositor_bytes(&self) -> Option<(u64, usize)> {
        let r = self.rs.renderer.read();
        let c = r.callback_resources.get::<Resources>()?.compositor.as_ref()?;
        Some((c.resident_bytes(), c.fx_cache_bytes().saturating_add(usize::try_from(c.composite_cache_bytes()).unwrap_or(usize::MAX))))
    }

    /// Whether `doc`'s layers fit the budget as it now stands, measured without a refresh (a GPU
    /// Memory change shows in the status bar at once). `None` before the compositor exists.
    pub fn measure_fit(&self, doc: &photocraft_doc::Document) -> Option<LayerFit> {
        let mut r = self.rs.renderer.write();
        let res = r.callback_resources.get_mut::<Resources>()?;
        let budget = res.compositor_budget;
        let comp = res.compositor.as_mut()?;
        if let Some(b) = budget {
            comp.set_memory_budget(b);
        }
        let fit = LayerFit { doc: doc.id.0, needed: comp.working_set(doc, doc.bounds()), budget: comp.resident_budget() };
        res.layer_fit = Some(fit);
        Some(fit)
    }

    /// Whether the layers of the last full (or large) refresh fit the GPU memory budget, and by
    /// how much (`None` before the first one).
    pub fn layer_fit(&self) -> Option<LayerFit> {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<Resources>()?.layer_fit
    }

    /// Set the checkerboard and gamut warning colours.
    pub fn set_style(&self, style: CanvasStyle) {
        let mut r = self.rs.renderer.write();
        if let Some(res) = r.callback_resources.get_mut::<Resources>() {
            res.style = style;
        }
    }

    /// Whether document `doc` has been uploaded with this size.
    pub fn has(&self, doc: u64, size: [u32; 2]) -> bool {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<Resources>().and_then(|res| res.docs.get(&doc)).is_some_and(|d| d.size == size)
    }

    /// Whether [`GpuCanvas::composite`] would draw `doc` with the wgpu compositor (rather than
    /// fall back to the CPU compositor).
    pub fn supports(&self, doc: &photocraft_doc::Document) -> bool {
        if std::env::var_os("PHOTOCRAFT_CPU_COMPOSE").is_some() || doc.size.width == 0 || doc.size.height == 0 {
            return false;
        }
        let r = self.rs.renderer.read();
        let Some(res) = r.callback_resources.get::<Resources>() else { return false };
        if res.compositor_failed.is_some() {
            return false;
        }
        match &res.compositor {
            Some(c) => c.supports(doc).is_ok(),
            // Layers larger than the texture limit are stored in pages, so any size qualifies.
            None => photocraft_gpu::plan(doc).is_ok(),
        }
    }

    /// Replace the whole document image with an `Rgba8Unorm` texture. `rgba` is premultiplied
    /// RGBA8, `size[0] * size[1] * 4` bytes (anything else is ignored).
    pub fn upload_full(&self, doc: u64, size: [u32; 2], rgba: &[u8]) {
        self.upload_full_as(doc, size, FORMAT, rgba);
    }

    /// Replace the whole document image with a `format` texture of premultiplied `texels`.
    fn upload_full_as(&self, doc: u64, size: [u32; 2], format: wgpu::TextureFormat, texels: &[u8]) {
        if size[0] == 0 || size[1] == 0 || texels.len() as u64 != size[0] as u64 * size[1] as u64 * texel_bytes(format) || !self.health.is_ok() {
            return;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return };
        if res.docs.get(&doc).is_none_or(|d| d.size != size || d.format != format) {
            let Some(tex) = DocTextures::new(device, res, size, self.tile, format) else {
                res.docs.remove(&doc);
                return;
            };
            res.docs.insert(doc, tex);
        }
        let Some(d) = res.docs.get(&doc) else { return };
        d.write(queue, [0, 0], size, size[0], texels);
        d.regenerate_mips(device, queue, res, [0, 0, size[0], size[1]]);
    }

    /// Replace a rectangle `origin..origin+size` of an uploaded document with premultiplied texels
    /// in its texture format (`size[0] * size[1]` texels: RGBA8 or RGBA16F). Returns false if the
    /// document isn't uploaded, the rectangle doesn't fit or the buffer has the wrong size.
    pub fn upload_rect(&self, doc: u64, origin: [u32; 2], size: [u32; 2], texels: &[u8]) -> bool {
        if !self.health.is_ok() {
            return false;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return false };
        let Some(d) = res.docs.get(&doc) else { return false };
        if texels.len() as u64 != size[0] as u64 * size[1] as u64 * texel_bytes(d.format)
            || origin[0].saturating_add(size[0]) > d.size[0]
            || origin[1].saturating_add(size[1]) > d.size[1]
        {
            return false;
        }
        if size[0] == 0 || size[1] == 0 {
            return true;
        }
        d.write(queue, origin, size, size[0], texels);
        d.regenerate_mips(device, queue, res, [origin[0], origin[1], origin[0] + size[0], origin[1] + size[1]]);
        true
    }

    /// The texture format of uploaded document `doc`.
    fn format_of(&self, doc: u64) -> Option<wgpu::TextureFormat> {
        let r = self.rs.renderer.read();
        r.callback_resources.get::<Resources>().and_then(|res| res.docs.get(&doc)).map(|d| d.format)
    }

    /// Upload a CPU composite covering the whole document (a preview of a document of `depth`:
    /// see [`GpuCanvas::format_for`]).
    pub fn upload_buffer_full(&self, doc: u64, buf: &photocraft_compose::Buffer, depth: photocraft_doc::SampleType) {
        let size = [buf.rect.width(), buf.rect.height()];
        let format = self.format_for(depth, size);
        self.upload_full_as(doc, size, format, &texels(format, &buf.px));
    }

    /// Upload a CPU composite of a sub-rectangle (in document pixels, `buf.rect`).
    pub fn upload_buffer_rect(&self, doc: u64, buf: &photocraft_compose::Buffer) -> bool {
        let r = buf.rect;
        let Some(format) = self.format_of(doc) else { return false };
        if r.x0 < 0 || r.y0 < 0 {
            return false;
        }
        self.upload_rect(doc, [r.x0 as u32, r.y0 as u32], [r.width(), r.height()], &texels(format, &buf.px))
    }

    /// Composite `region` of `doc` with the wgpu compositor straight into its display texture
    /// (no CPU pixels, no upload of the composite). `encode_srgb` stores the sRGB encoding of the
    /// composite (linear documents, see `photocraft_engine::display_color`). Returns `Err` when the
    /// document uses features the GPU compositor doesn't cover yet; the caller then falls back to
    /// the CPU compositor.
    pub fn composite(
        &self,
        doc: &photocraft_doc::Document,
        region: photocraft_geom::Rect,
        encode_srgb: bool,
    ) -> Result<photocraft_gpu::Stats, photocraft_gpu::Unsupported> {
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let size = [doc.size.width, doc.size.height];
        if size[0] == 0 || size[1] == 0 {
            return Err(photocraft_gpu::Unsupported("empty document".into()));
        }
        if std::env::var_os("PHOTOCRAFT_CPU_COMPOSE").is_some() {
            return Err(photocraft_gpu::Unsupported("disabled by PHOTOCRAFT_CPU_COMPOSE".into()));
        }
        if let Some(f) = self.fault() {
            return Err(photocraft_gpu::Unsupported(f.to_string()));
        }
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return Err(photocraft_gpu::Unsupported("no GPU canvas".into())) };
        // A driver that couldn't build the pipelines once won't later: stay on the CPU compositor.
        if let Some(e) = &res.compositor_failed {
            return Err(e.clone());
        }
        let mut comp = match res.compositor.take() {
            Some(c) => c,
            None => match photocraft_gpu::Compositor::try_new_with_format(device, photocraft_gpu::Compositor::preferred_acc_format(&self.rs.adapter)) {
                Ok(c) => c,
                Err(e) => {
                    log::warn!("{e}; using the CPU compositor");
                    res.compositor_failed = Some(e.clone());
                    return Err(e);
                }
            },
        };
        comp.set_health(self.health.clone());
        // Measured, not waited for: the timestamps come back a frame or two later.
        comp.measure_gpu_time(device, queue);
        if let Some(b) = res.compositor_budget {
            comp.set_memory_budget(b);
        }
        if let Some(b) = res.compositor_cache_budget {
            comp.set_composite_cache_budget(b);
        }
        comp.set_focus(res.compositor_focus);
        let key = doc.id.0;
        let format = self.format_for(doc.depth, size);
        let fresh = res.docs.get(&key).is_none_or(|d| d.size != size || d.format != format);
        let region = if fresh { doc.bounds() } else { region.intersect(&doc.bounds()) };
        // Checked before allocating a new canvas texture only: `render` plans (and refuses) itself.
        if fresh && let Err(e) = comp.supports(doc) {
            res.compositor = Some(comp);
            return Err(e);
        }
        // A full refresh whose layer pages don't fit the memory budget would re-upload the
        // evicted ones every time (no faster than the CPU, and more memory): the banded CPU
        // compositor does it (in the background on desktop). So does a large damage rect, such
        // as hiding a big layer (#4024); small edits in the view stay on the GPU.
        let large = region.width() as u64 * region.height() as u64 >= DEFER_PX;
        if region == doc.bounds() || large {
            let fit = LayerFit { doc: doc.id.0, needed: comp.working_set(doc, region), budget: comp.resident_budget() };
            res.layer_fit = Some(fit);
            if !fit.fits() {
                res.compositor = Some(comp);
                return Err(photocraft_gpu::Unsupported(OVER_BUDGET.into()));
            }
        }
        if fresh {
            let Some(tex) = DocTextures::new(device, res, size, self.tile, format) else {
                res.docs.remove(&key);
                res.compositor = Some(comp);
                return Err(photocraft_gpu::Unsupported(OVER_CANVAS_BUDGET.into()));
            };
            res.docs.insert(key, tex);
        }
        let (Some(pipe), Some(d)) = (res.encode_pipeline(format), res.docs.get(&key)) else {
            res.compositor = Some(comp);
            return Err(photocraft_gpu::Unsupported(format!("no {format:?} canvas texture or pipeline")));
        };
        let bgl = &res.encode_bgl;
        // A float canvas keeps values above 1.0 (32-bit documents, for the 32-bit preview).
        let keep_hdr = i32::from(format == FORMAT_HIGH);
        // Last-resort guard: a wgpu panic (e.g. polling a device lost mid-refresh) marks the
        // device lost instead of taking the app and its documents down.
        let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            comp.render(device, queue, doc, region, |enc, out| {
                for t in &d.tiles {
                    let [tx, ty, tw, th] = t.rect.map(|v| v as i32);
                    let r = out.rect.intersect(&photocraft_geom::Rect::from_xywh(tx, ty, tw as u32, th as u32));
                    if r.is_empty() {
                        continue;
                    }
                    let offset = [out.rect.x0 - tx, out.rect.y0 - ty, i32::from(encode_srgb), keep_hdr];
                    let ubuf = init_buffer(device, "pc_encode", &offset.iter().flat_map(|v| v.to_le_bytes()).collect::<Vec<u8>>(), wgpu::BufferUsages::UNIFORM);
                    let bg = device.create_bind_group(&wgpu::BindGroupDescriptor {
                        label: Some("pc_encode"),
                        layout: bgl,
                        entries: &[
                            wgpu::BindGroupEntry { binding: 0, resource: wgpu::BindingResource::TextureView(out.view) },
                            wgpu::BindGroupEntry { binding: 1, resource: ubuf.as_entire_binding() },
                        ],
                    });
                    let mut pass = enc.begin_render_pass(&wgpu::RenderPassDescriptor {
                        label: Some("pc_encode"),
                        color_attachments: &[Some(wgpu::RenderPassColorAttachment {
                            view: &t.levels[0],
                            resolve_target: None,
                            depth_slice: None,
                            ops: wgpu::Operations { load: wgpu::LoadOp::Load, store: wgpu::StoreOp::Store },
                        })],
                        depth_stencil_attachment: None,
                        timestamp_writes: None,
                        occlusion_query_set: None,
                        multiview_mask: None,
                    });
                    pass.set_pipeline(pipe);
                    pass.set_bind_group(0, &bg, &[]);
                    pass.set_scissor_rect((r.x0 - tx) as u32, (r.y0 - ty) as u32, r.width(), r.height());
                    pass.draw(0..3, 0..1);
                }
            })
        }));
        let Ok(result) = result else {
            self.health.mark(photocraft_gpu::Fault::Lost("the GPU compositor stopped (internal error)".into()));
            res.docs.remove(&key);
            return Err(photocraft_gpu::Unsupported("GPU device lost".into()));
        };
        // Lost during the refresh: its output can't be trusted.
        let result = match self.fault() {
            Some(f) => Err(photocraft_gpu::Unsupported(f.to_string())),
            None => result,
        };
        if result.is_ok() {
            d.regenerate_mips(device, queue, res, [region.x0 as u32, region.y0 as u32, region.x1 as u32, region.y1 as u32]);
            if std::env::var_os("PHOTOCRAFT_GPU_SYNC").is_some() {
                // Benchmarking: wait for the GPU so callers can time the whole refresh.
                #[cfg(not(target_arch = "wasm32"))]
                self.health.wait(device, None);
            }
        } else if fresh {
            res.docs.remove(&key);
        }
        res.compositor = Some(comp);
        result
    }

    /// Bring document `key`'s display texture up to date with `doc`: only `damage` when given (a
    /// brush stroke on an already uploaded document), else everything. The wgpu compositor renders
    /// straight into the texture when it supports the document; otherwise the CPU compositor does.
    /// `display` is the canvas colour transform: the GPU path stores the sRGB encoding when it
    /// asks for it, and every CPU band or rect goes through its `texture_buffer`.
    pub fn refresh(
        &self,
        key: u64,
        doc: &photocraft_doc::Document,
        damage: Option<photocraft_geom::Rect>,
        display: Option<&photocraft_engine::display_color::CanvasDisplay>,
    ) -> Refresh {
        self.refresh_with(key, doc, damage, display, false)
    }

    /// [`GpuCanvas::refresh`], except that with `defer`, a refresh of at least [`DEFER_PX`] the
    /// CPU compositor would draw is left to the caller (`background_redraw`): the texture is made
    /// ready (keeping what it shows when it already fits) and the kind is [`REFRESH_DEFERRED`].
    pub fn refresh_with(
        &self,
        key: u64,
        doc: &photocraft_doc::Document,
        damage: Option<photocraft_geom::Rect>,
        display: Option<&photocraft_engine::display_color::CanvasDisplay>,
        defer: bool,
    ) -> Refresh {
        if let Some(f) = self.fault() {
            // Nothing reaches the GPU any more; the app switches to the CPU canvas.
            return Refresh { kind: "lost", fallback: Some(f.to_string()), ..Default::default() };
        }
        if !self.fits_canvas(doc) {
            // Neither compositor can fill textures that are never created: the CPU canvas draws
            // it. A set left from before the canvas grew is stale, so it goes too.
            if let Some(res) = self.rs.renderer.write().callback_resources.get_mut::<Resources>() {
                res.docs.remove(&key);
            }
            return Refresh { kind: REFRESH_OVER_BUDGET, fallback: Some(OVER_CANVAS_BUDGET.into()), ..Default::default() };
        }
        let bounds = doc.bounds();
        let size = [doc.size.width, doc.size.height];
        let format = self.format_for(doc.depth, size);
        let damage = damage.filter(|_| self.has(key, size) && self.format_of(key) == Some(format)).map(|r| r.intersect(&bounds));
        let t0 = now_ms();
        let mut out = Refresh::default();
        if damage.is_some_and(|r| r.is_empty()) {
            // Nothing changed on the canvas (selecting a layer, say): don't even plan.
            out.kind = "rect";
            return out;
        }
        let region = damage.unwrap_or(bounds);
        let encode_srgb = display.is_some_and(|d| d.encode_srgb);
        let gpu = if key == doc.id.0 { self.composite(doc, region, encode_srgb) } else { Err(photocraft_gpu::Unsupported("preview texture".into())) };
        match gpu {
            Ok(stats) => {
                out.kind = if damage.is_some() { "gpu-rect" } else { "gpu-full" };
                out.px = region.width() as u64 * region.height() as u64;
                // Encoding and submitting only: the GPU is still running this work.
                out.composite_ms = now_ms() - t0;
                out.uploads = stats.tiles_uploaded as u64;
                out.gpu = stats.gpu_time;
                return out;
            }
            Err(e) => out.fallback = Some(e.0),
        }
        let px = region.width() as u64 * region.height() as u64;
        if defer && px >= DEFER_PX && self.prepare_texture(key, doc).is_some() {
            out.kind = REFRESH_DEFERRED;
            out.px = px;
            return out;
        }
        if let Some(r) = damage {
            if r.is_empty() {
                out.kind = "rect";
                return out;
            }
            let buf = photocraft_compose::render(doc, r);
            let t1 = now_ms();
            if self.upload_buffer_rect(key, &texture_buffer(display, &buf)) {
                out.kind = "rect";
                out.px = r.width() as u64 * r.height() as u64;
                out.composite_ms = t1 - t0;
                out.upload_ms = now_ms() - t1;
                return out;
            }
        }
        self.upload_composite(key, doc, display);
        out.kind = "full";
        out.px = bounds.width() as u64 * bounds.height() as u64;
        out.composite_ms = now_ms() - t0;
        out
    }

    /// Composite the whole of `doc` with the CPU compositor into document `key`'s texture, band by
    /// band (each band converted and uploaded before the next is rendered), so a huge document
    /// never needs a full-size float composite or texture-format copy in memory.
    pub fn upload_composite(&self, key: u64, doc: &photocraft_doc::Document, display: Option<&photocraft_engine::display_color::CanvasDisplay>) {
        let size = [doc.size.width, doc.size.height];
        let Some(format) = self.prepare_texture(key, doc) else { return };
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut rgba = Vec::new();
        let _ = photocraft_compose::render_bands(doc, doc.bounds(), 0, |band| -> Result<(), ()> {
            if !self.health.is_ok() {
                return Err(());
            }
            texels_into(format, &texture_buffer(display, &band).px, &mut rgba);
            let renderer = self.rs.renderer.read();
            let d = renderer.callback_resources.get::<Resources>().and_then(|r| r.docs.get(&key)).ok_or(())?;
            d.write(queue, [0, band.rect.y0 as u32], [size[0], band.rect.height()], size[0], &rgba);
            drop(renderer);
            // Flush the staged band so its staging memory is reclaimed while the next renders.
            queue.submit(std::iter::empty::<wgpu::CommandBuffer>());
            self.health.poll(device);
            Ok(())
        });
        if !self.health.is_ok() {
            return;
        }
        let mut renderer = self.rs.renderer.write();
        if let Some(res) = renderer.callback_resources.get_mut::<Resources>()
            && let Some(d) = res.docs.get(&key)
        {
            d.regenerate_mips(device, queue, res, [0, 0, size[0], size[1]]);
        }
    }

    /// Make sure document `key` has a display texture of `doc`'s size and format, keeping the one
    /// it has when that fits. Returns its format, or `None` when it can't be created.
    pub fn prepare_texture(&self, key: u64, doc: &photocraft_doc::Document) -> Option<wgpu::TextureFormat> {
        let size = [doc.size.width, doc.size.height];
        if size[0] == 0 || size[1] == 0 || !self.health.is_ok() {
            return None;
        }
        let format = self.format_for(doc.depth, size);
        let mut renderer = self.rs.renderer.write();
        let res = renderer.callback_resources.get_mut::<Resources>()?;
        if res.docs.get(&key).is_none_or(|d| d.size != size || d.format != format) {
            let Some(tex) = DocTextures::new(&self.rs.device, res, size, self.tile, format) else {
                res.docs.remove(&key);
                return None;
            };
            res.docs.insert(key, tex);
        }
        Some(format)
    }

    /// Free textures, display LUTs and their signatures for documents not in `live`.
    pub fn retain(&self, live: &[u64]) {
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return };
        if res.docs.keys().any(|k| !live.contains(k)) {
            res.docs.retain(|k, _| live.contains(k));
        }
        // Everything the compositor holds for documents that aren't open, also when their
        // texture entry was dropped earlier (over budget, a failed render), which used to leave
        // their pages and effect maps resident after closing (#4529).
        if let Some(c) = res.compositor.as_mut() {
            c.retain_docs(|d| live.contains(&d.0));
        }
        // LUTs and identity-transform signatures can outlive document textures. Prune both,
        // or a preserved-ID reopen can skip rebuilding a missing LUT.
        res.luts.retain(|k, _| live.contains(&k.0));
        res.display_lut_signatures.retain(|k, _| live.contains(&k.0));
    }

    pub(crate) fn display_lut_signature(&self, doc: u64, output: u32) -> Option<(u64, u8)> {
        let renderer = self.rs.renderer.read();
        renderer.callback_resources.get::<Resources>()?.display_lut_signatures.get(&(doc, output)).copied()
    }

    /// Whether document `doc` has a display LUT for display `output` (tests).
    #[cfg(test)]
    pub(crate) fn has_display_lut(&self, doc: u64, output: u32) -> bool {
        let renderer = self.rs.renderer.read();
        renderer.callback_resources.get::<Resources>().is_some_and(|r| r.luts.contains_key(&(doc, output)))
    }

    pub(crate) fn cache_display_lut_signature(&self, doc: u64, output: u32, signature: u64, mode: u8) {
        let mut renderer = self.rs.renderer.write();
        if let Some(res) = renderer.callback_resources.get_mut::<Resources>() {
            res.display_lut_signatures.insert((doc, output), (signature, mode));
        }
    }

    /// Set (or clear with `None`) the display LUT of document `doc` on display `output`:
    /// `size`³ RGBA8 texels, red fastest. RGB is the display colour for each lattice input;
    /// alpha 255 marks out-of-gamut colours for the gamut warning.
    pub fn set_display_lut(&self, doc: u64, output: u32, size: u32, rgba: Option<&[u8]>) {
        if !self.health.is_ok() {
            return;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return };
        res.display_lut_signatures.remove(&(doc, output));
        match rgba {
            None => {
                res.luts.remove(&(doc, output));
            }
            Some(bytes) => {
                if size < 2 || bytes.len() as u64 != (size as u64).pow(3) * 4 {
                    log::warn!("set_display_lut: {} bytes for a {size}³ LUT; ignored", bytes.len());
                    return;
                }
                let bg = lut_bind_group(device, queue, &res.lut_bgl, size, bytes, None);
                res.luts.insert((doc, output), bg);
            }
        }
    }

    /// Set a separately sampled curve/matrix/curve display transform. CMS validates this
    /// representation and provides bounded tables; no profile interpretation lives in the UI.
    pub fn set_display_matrix_shaper(&self, doc: u64, output: u32, shaper: &photocraft_cms::GpuMatrixShaper) {
        if !self.health.is_ok() {
            return;
        }
        let mut renderer = self.rs.renderer.write();
        let Some(res) = renderer.callback_resources.get_mut::<Resources>() else { return };
        let bg = lut_bind_group(&self.rs.device, &self.rs.queue, &res.lut_bgl, 2, &identity_lut_bytes(), Some(shaper));
        res.display_lut_signatures.remove(&(doc, output));
        res.luts.insert((doc, output), bg);
    }

    /// Read back level 0 of document `key`'s canvas texture: its format, size and the stored
    /// (premultiplied) texels as `f32` RGBA, row-major. Waits for the GPU; for tests, benchmarks
    /// and debugging.
    #[cfg(not(target_arch = "wasm32"))]
    pub fn read_texels(&self, key: u64) -> Option<(wgpu::TextureFormat, [u32; 2], Vec<[f32; 4]>)> {
        if !self.health.is_ok() {
            return None;
        }
        let (device, queue) = (&self.rs.device, &self.rs.queue);
        let renderer = self.rs.renderer.read();
        let d = renderer.callback_resources.get::<Resources>()?.docs.get(&key)?;
        let bpp = texel_bytes(d.format);
        let (w, h) = (d.size[0] as usize, d.size[1] as usize);
        let mut out = vec![[0.0f32; 4]; w.checked_mul(h)?];
        for t in &d.tiles {
            let [tx, ty, tw, th] = t.rect;
            let row = (tw as u64 * bpp).next_multiple_of(wgpu::COPY_BYTES_PER_ROW_ALIGNMENT as u64);
            let buf = device.create_buffer(&wgpu::BufferDescriptor {
                label: Some("pc_canvas_readback"),
                size: row * th as u64,
                usage: wgpu::BufferUsages::COPY_DST | wgpu::BufferUsages::MAP_READ,
                mapped_at_creation: false,
            });
            let mut enc = device.create_command_encoder(&wgpu::CommandEncoderDescriptor { label: Some("pc_canvas_readback") });
            enc.copy_texture_to_buffer(
                t.texture.as_image_copy(),
                wgpu::TexelCopyBufferInfo {
                    buffer: &buf,
                    layout: wgpu::TexelCopyBufferLayout { offset: 0, bytes_per_row: Some(row as u32), rows_per_image: Some(th) },
                },
                wgpu::Extent3d { width: tw, height: th, depth_or_array_layers: 1 },
            );
            queue.submit([enc.finish()]);
            let slice = buf.slice(..);
            slice.map_async(wgpu::MapMode::Read, |_| {});
            if !self.health.wait(device, None) {
                return None;
            }
            let data = slice.get_mapped_range().ok()?;
            for y in 0..th as usize {
                let src = data.get(y * row as usize..)?;
                for x in 0..tw as usize {
                    let o = out.get_mut((ty as usize + y) * w + tx as usize + x)?;
                    *o = texel_to_f32(d.format, src.get(x * bpp as usize..(x + 1) * bpp as usize)?);
                }
            }
        }
        Some((d.format, d.size, out))
    }

    /// Add the paint callback drawing `params` into `rect` (clipped by the painter's clip rect).
    pub fn paint(painter: &egui::Painter, rect: egui::Rect, params: ViewParams) {
        painter.add(egui_wgpu::Callback::new_paint_callback(rect, CanvasCallback { rect, params }));
    }
}

/// A CPU composite as the canvas texture stores it (`display`'s encoding; as is without one).
fn texture_buffer<'a>(
    display: Option<&photocraft_engine::display_color::CanvasDisplay>,
    buf: &'a photocraft_compose::Buffer,
) -> std::borrow::Cow<'a, photocraft_compose::Buffer> {
    match display {
        Some(d) => d.texture_buffer(buf),
        None => std::borrow::Cow::Borrowed(buf),
    }
}

/// A CPU composite `buf` as texels of a `format` canvas texture, in `display`'s encoding: what
/// [`GpuCanvas::upload_rect`] takes. Runs anywhere (a redraw's worker converts its own pieces).
pub fn display_texels(
    format: wgpu::TextureFormat,
    display: Option<&photocraft_engine::display_color::CanvasDisplay>,
    buf: &photocraft_compose::Buffer,
) -> Vec<u8> {
    texels(format, &texture_buffer(display, buf).px)
}

/// What a [`GpuCanvas::refresh`] did.
#[derive(Clone, Debug, Default)]
pub struct Refresh {
    /// "gpu-rect", "gpu-full" (wgpu compositor), "rect" or "full" (CPU compositor); "lost" or
    /// [`REFRESH_OVER_BUDGET`] when nothing was drawn and the caller should use the CPU canvas.
    pub kind: &'static str,
    /// Pixels refreshed.
    pub px: u64,
    pub composite_ms: f64,
    pub upload_ms: f64,
    /// Layer tiles the wgpu compositor uploaded.
    pub uploads: u64,
    /// How long the GPU spent executing a recent wgpu composite, once its timestamps came back
    /// (a frame or two after that refresh, so usually an earlier one than this). It carries its
    /// own pixel count and is never this refresh's unless they match. `None` when the device has
    /// no timestamp queries, on the CPU compositor, and on wasm: no number at all is reported
    /// rather than `composite_ms`, which measures encoding and submitting, not executing. It
    /// leaves out layer-tile uploads (`uploads` above counts them), so a first refresh of a
    /// document under-reports by more than the few per cent of a warm one.
    pub gpu: Option<photocraft_gpu::GpuTiming>,
    /// Why the wgpu compositor wasn't used.
    pub fallback: Option<String>,
}

/// How the app creates its wgpu device: egui's defaults clamped to the adapter's supported limits,
/// with the adapter's own texture and buffer sizes rather than egui's 8192 px cap, so large
/// documents stay on the GPU compositor.
pub fn wgpu_setup() -> egui_wgpu::WgpuSetup {
    let mut setup = egui_wgpu::WgpuSetup::without_display_handle();
    use_adapter_limits(&mut setup);
    setup
}

/// Make `setup` request the adapter's own texture and buffer size limits instead of egui's
/// default 8192 px cap (which sent every document wider or taller than 8192 px to the CPU
/// compositor). Other limits use egui's defaults (WebGL2's on GL), clamped to adapter support;
/// features stay egui's default.
pub fn use_adapter_limits(setup: &mut egui_wgpu::WgpuSetup) {
    use_adapter_limits_with(setup, |_| {});
}

/// [`use_adapter_limits`], calling `on_adapter` with the chosen adapter just before the device
/// is requested (the desktop app records it in its crash-safe startup marker).
pub fn use_adapter_limits_with(setup: &mut egui_wgpu::WgpuSetup, on_adapter: impl Fn(&wgpu::Adapter) + Send + Sync + 'static) {
    if let egui_wgpu::WgpuSetup::CreateNew(create) = setup {
        create.device_descriptor = std::sync::Arc::new(move |adapter| {
            on_adapter(adapter);
            device_descriptor(adapter)
        });
    }
}

/// How the app asks for its device: egui's defaults, the adapter's texture and buffer size
/// limits ([`device_limits`]), and timestamp queries where the adapter has them, so the canvas
/// can report how long the GPU actually spends compositing ([`photocraft_gpu::GpuTimer`]).
/// A bench or test that builds its own device should use this rather than [`device_limits`]
/// alone, or it measures a device the app never creates. (`bevel_bench`, `fx_bench` and
/// `interactive_bench` still call [`device_limits`] directly and so report no GPU time.)
pub fn device_descriptor(adapter: &wgpu::Adapter) -> wgpu::DeviceDescriptor<'static> {
    wgpu::DeviceDescriptor {
        label: Some("photocraft wgpu device"),
        required_limits: device_limits(adapter),
        required_features: timing_features(adapter),
        ..Default::default()
    }
}

/// The timestamp-query features when the adapter supports all of them, else none: asking for a
/// feature an adapter lacks fails device creation, and a canvas without GPU timing is far better
/// than no canvas.
///
/// `PHOTOCRAFT_NO_GPU_TIMING` suppresses the request as well as the timer
/// ([`photocraft_gpu::Compositor::measure_gpu_time`]), so the variable also rescues a driver
/// that advertises the features and then fails or misbehaves on device creation — not only one
/// whose timestamps come back wrong.
pub fn timing_features(adapter: &wgpu::Adapter) -> wgpu::Features {
    let want = photocraft_gpu::timing::FEATURES;
    if std::env::var_os("PHOTOCRAFT_NO_GPU_TIMING").is_some() {
        return wgpu::Features::empty();
    }
    if adapter.features().contains(want) { want } else { wgpu::Features::empty() }
}

/// egui's base limits (WebGL2's on GL), clamped to adapter support, with its maximum texture and buffer sizes.
pub fn device_limits(adapter: &wgpu::Adapter) -> wgpu::Limits {
    device_limits_for(adapter.get_info().backend, adapter.limits())
}

fn device_limits_for(backend: wgpu::Backend, supported: wgpu::Limits) -> wgpu::Limits {
    let base = if backend == wgpu::Backend::Gl { wgpu::Limits::downlevel_webgl2_defaults() } else { wgpu::Limits::default() };
    let base = base.or_worse_values_from(&supported);
    wgpu::Limits { max_texture_dimension_2d: supported.max_texture_dimension_2d, max_buffer_size: supported.max_buffer_size, ..base }
}

/// Milliseconds since first call (monotonic). Always 0 on wasm, where `std::time` is unavailable.
pub fn now_ms() -> f64 {
    #[cfg(not(target_arch = "wasm32"))]
    {
        static START: std::sync::OnceLock<std::time::Instant> = std::sync::OnceLock::new();
        START.get_or_init(std::time::Instant::now).elapsed().as_secs_f64() * 1000.0
    }
    #[cfg(target_arch = "wasm32")]
    0.0
}

/// UI-thread timings (CPU side), exponentially smoothed.
#[derive(Clone, Debug, Default, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Perf {
    /// Average CPU time building the UI per frame (ms).
    pub ui_ms: f64,
    /// Worst UI frame of the last ~second (ms).
    pub ui_max_ms: f64,
    /// Last canvas refresh, CPU side (ms): the CPU composite on the CPU path, and on the GPU
    /// path the cost of *encoding and submitting* the composite — not of running it, which is
    /// `gpu_ms`.
    pub composite_ms: f64,
    /// Last canvas refresh: conversion + upload (ms).
    pub upload_ms: f64,
    /// Last canvas refresh kind: "full", "rect" or "none".
    pub last_refresh: &'static str,
    /// Pixels in the last refresh.
    pub last_refresh_px: u64,
    /// Whether the GPU canvas path is active.
    pub gpu: bool,
    /// Layer tiles uploaded by the last GPU composite.
    pub gpu_uploads: u64,
    /// How long the GPU spent executing a recent composite (ms), from timestamp queries read
    /// back after the fact. `None` on the CPU compositor, on a device without timestamp queries
    /// and on wasm — there is then no honest number to report, and `composite_ms` is not one.
    /// Excludes layer-tile uploads and end-of-batch work (see `photocraft_gpu::timing`), so it
    /// is a few per cent under the GPU's full share of a warm refresh and further under a cold
    /// one.
    pub gpu_ms: Option<f64>,
    /// Pixels of the refresh `gpu_ms` measured, which is a frame or two behind
    /// `last_refresh_px` and may be a different size.
    pub gpu_ms_px: u64,
    /// Why the last refresh fell back to the CPU compositor (None = GPU composited).
    pub gpu_fallback: Option<String>,
    /// Adapter, backend, driver and fallback state (Help › System Info).
    pub gpu_info: GpuInfo,
    /// GPU memory the compositor may hold for layer pages and effect maps (MB; see
    /// [`memory_budget`]).
    pub gpu_budget_mb: u64,
    /// The Memory Usage allowance and the GPU Memory preference (bytes) `gpu_budget_mb` was
    /// computed from.
    #[serde(skip)]
    pub gpu_budget_allowance: (u64, u64),
    /// The layer pages the last full refresh needed against the part of the budget they may
    /// hold; when they don't fit, edits that redraw the whole document do it on the CPU.
    pub gpu_layer_fit: Option<LayerFit>,
    /// Last command run through the app and its duration (ms).
    pub last_command: String,
    pub command_ms: f64,
    /// Most recent cost of occasional UI work (outline tracing, thumbnails, …), in ms.
    pub spans: std::collections::BTreeMap<&'static str, f64>,
    #[serde(skip)]
    max_decay: f64,
    /// Composite and upload time of this frame's canvas refreshes, in ms (the stroke trace).
    #[serde(skip)]
    pub(crate) frame_refresh_ms: f64,
}

/// What the app renders with and why (Help › System Info, Preferences › Performance, the `perf`
/// control-channel output).
#[derive(Clone, Debug, Default, PartialEq, serde::Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GpuInfo {
    /// Adapter name ("" before the window opens).
    pub adapter: String,
    /// wgpu backend of the window's device ("vulkan", "dx12", "metal", "gl", …).
    pub backend: String,
    /// Device type ("discreteGpu", "integratedGpu", "cpu", …).
    pub device_type: String,
    /// Driver name and version as the driver reports them.
    pub driver: String,
    /// The adapter's own memory in MB ([`video_memory`]): discrete GPUs where the platform
    /// reports it. It caps the GPU memory budgets.
    pub video_memory_mb: Option<u64>,
    /// `performance.gpuBackend` at launch.
    pub preference: String,
    /// Every graphics adapter the window could have used, by name (Preferences › Performance ›
    /// Graphics Adapter lists them). Empty in hosts that don't set it.
    pub adapters: Vec<String>,
    /// The backend startup chose ("auto", "dx12", "cpu", …, or "env" for `WGPU_BACKEND`).
    pub selected: String,
    /// Why startup didn't use the preference as is (previous start crashed, `--safe-gpu`,
    /// `WGPU_BACKEND`, Intel on Windows).
    pub fallback: Option<String>,
    /// "gpu" (wgpu canvas and compositor) or "cpu" (CPU compositor, egui textures).
    pub canvas: String,
    /// Why the GPU canvas was dropped during this session (device lost or a GPU error).
    pub lost: Option<String>,
    /// Present mode and frame latency ("fifo, latency 2"; launch overrides marked, see the
    /// app's `presentation`). Empty in hosts that don't set it.
    pub present: String,
}

impl GpuInfo {
    /// Record the adapters the instance found, without duplicates (one GPU shows up once per backend).
    pub fn set_available(&mut self, adapters: &[wgpu::Adapter]) {
        self.adapters.clear();
        for a in adapters {
            let name = a.get_info().name;
            if !name.is_empty() && !self.adapters.contains(&name) {
                self.adapters.push(name);
            }
        }
    }

    /// Fill the adapter fields from `info`.
    pub fn set_adapter(&mut self, info: &wgpu::AdapterInfo) {
        self.adapter = info.name.clone();
        self.backend = backend_name(info.backend).to_string();
        self.device_type = match info.device_type {
            wgpu::DeviceType::DiscreteGpu => "discreteGpu",
            wgpu::DeviceType::IntegratedGpu => "integratedGpu",
            wgpu::DeviceType::VirtualGpu => "virtualGpu",
            wgpu::DeviceType::Cpu => "cpu",
            wgpu::DeviceType::Other => "other",
        }
        .to_string();
        self.driver = [info.driver.as_str(), info.driver_info.as_str()].iter().filter(|s| !s.is_empty()).copied().collect::<Vec<_>>().join(" ");
        self.video_memory_mb = video_memory(info).map(|b| b >> 20);
    }

    /// Human-readable lines for Help › System Info.
    pub fn lines(&self) -> Vec<String> {
        let or = |s: &str, d: &str| if s.is_empty() || (s == "auto" && d == "auto") { tl!(d).to_string() } else { s.to_string() };
        let mut v = vec![
            {
                let template = "Graphics adapter: {adapter}";
                crate::i18n::fmt(tl!(template), &[("adapter", &or(&self.adapter, "unknown"))])
            },
            {
                let template = "Backend: {backend} ({type})";
                crate::i18n::fmt(tl!(template), &[("backend", &or(&self.backend, "unknown")), ("type", &or(&self.device_type, "unknown type"))])
            },
            {
                let template = "Driver: {driver}";
                crate::i18n::fmt(tl!(template), &[("driver", &or(&self.driver, "unknown"))])
            },
        ];
        // The card's own memory caps the GPU budgets, so it explains a huge canvas falling back
        // to the CPU. Only discrete cards report one (integrated GPUs share system memory).
        if let Some(mb) = self.video_memory_mb {
            let template = "Graphics memory: {size}";
            v.push(crate::i18n::fmt(tl!(template), &[("size", &crate::chrome_ui::fmt_bytes(mb.saturating_mul(1 << 20)))]));
        }
        v.extend([
            {
                let template = "GPU backend preference: {backend}";
                crate::i18n::fmt(tl!(template), &[("backend", &or(&self.preference, "auto"))])
            },
            {
                let template = "Selected at launch: {backend}";
                crate::i18n::fmt(tl!(template), &[("backend", &or(&self.selected, "auto"))])
            },
            {
                let template = "Image compositor: {processor}";
                crate::i18n::fmt(tl!(template), &[("processor", if self.canvas == "gpu" { "GPU" } else { "CPU" })])
            },
            {
                let template = "Window renderer: {renderer}";
                let renderer = if self.device_type == "cpu" {
                    "Software adapter"
                } else if self.adapter.is_empty() {
                    "Unknown"
                } else {
                    "Graphics adapter"
                };
                crate::i18n::fmt(tl!(template), &[("renderer", tl!(renderer))])
            },
        ]);
        if let Some(f) = &self.fallback {
            v.push({
                let template = "Fallback: {reason}";
                crate::i18n::fmt(tl!(template), &[("reason", f)])
            });
        }
        if let Some(l) = &self.lost {
            v.push({
                let template = "This session: {reason}";
                crate::i18n::fmt(tl!(template), &[("reason", l)])
            });
        }
        v
    }
}

/// The preference name of a wgpu backend.
pub fn backend_name(b: wgpu::Backend) -> &'static str {
    match b {
        wgpu::Backend::Vulkan => "vulkan",
        wgpu::Backend::Dx12 => "dx12",
        wgpu::Backend::Metal => "metal",
        wgpu::Backend::Gl => "gl",
        wgpu::Backend::BrowserWebGpu => "webgpu",
        wgpu::Backend::Noop => "noop",
    }
}

impl Perf {
    pub fn record(&mut self, kind: &'static str, px: u64, composite_ms: f64, upload_ms: f64) {
        self.frame_refresh_ms += composite_ms + upload_ms;
        self.last_refresh = kind;
        self.last_refresh_px = px;
        self.composite_ms = composite_ms;
        self.upload_ms = upload_ms;
        if !kind.starts_with("gpu") {
            self.gpu_uploads = 0;
            // The CPU compositor did this one: there is no GPU time, and the last GPU
            // refresh's would be read as this refresh's.
            self.gpu_ms = None;
            self.gpu_ms_px = 0;
        } else {
            self.gpu_fallback = None;
        }
    }

    /// Record a canvas refresh and any GPU measurement that came back with it.
    pub fn record_refresh(&mut self, r: &Refresh) {
        self.record(r.kind, r.px, r.composite_ms, r.upload_ms);
        if let Some(t) = r.gpu {
            self.record_gpu(t);
        }
    }

    /// Record a GPU composite measurement that came back (see [`photocraft_gpu::GpuTiming`]).
    pub fn record_gpu(&mut self, t: photocraft_gpu::GpuTiming) {
        self.gpu_ms = Some(t.ms);
        self.gpu_ms_px = t.px;
    }
    pub fn span(&mut self, name: &'static str, ms: f64) {
        self.spans.insert(name, (ms * 100.0).round() / 100.0);
    }
    pub fn frame(&mut self, ms: f64) {
        self.ui_ms = if self.ui_ms == 0.0 { ms } else { self.ui_ms * 0.9 + ms * 0.1 };
        self.max_decay += 1.0;
        if ms > self.ui_max_ms || self.max_decay > 60.0 {
            self.ui_max_ms = ms;
            self.max_decay = 0.0;
        }
    }
}

/// Straight-alpha f32 RGBA (sRGB-encoded) → premultiplied RGBA8, split across threads on native.
pub fn premultiply_rgba8(px: &[[f32; 4]]) -> Vec<u8> {
    let mut out = Vec::new();
    texels_into(FORMAT, px, &mut out);
    out
}

/// Straight-alpha f32 RGBA (sRGB-encoded) → premultiplied RGBA16F (little-endian), split across
/// threads on native. Colour values above 1.0 are kept (32-bit documents); negatives and NaN
/// become 0.
pub fn premultiply_rgba16f(px: &[[f32; 4]]) -> Vec<u8> {
    let mut out = Vec::new();
    texels_into(FORMAT_HIGH, px, &mut out);
    out
}

/// Bytes per texel of a canvas texture format.
fn texel_bytes(format: wgpu::TextureFormat) -> u64 {
    if format == FORMAT_HIGH { 8 } else { 4 }
}

/// Straight-alpha f32 RGBA → premultiplied texels of `format`.
fn texels(format: wgpu::TextureFormat, px: &[[f32; 4]]) -> Vec<u8> {
    let mut out = Vec::new();
    texels_into(format, px, &mut out);
    out
}

/// [`texels`] into `out` (resized; reusing it across bands saves page-faulting a fresh buffer).
fn texels_into(format: wgpu::TextureFormat, px: &[[f32; 4]], out: &mut Vec<u8>) {
    fn rgba8(src: &[[f32; 4]], dst: &mut [u8]) {
        for (o, p) in dst.as_chunks_mut::<4>().0.iter_mut().zip(src) {
            let a = p[3].clamp(0.0, 1.0);
            o[0] = (p[0].clamp(0.0, 1.0) * a * 255.0 + 0.5) as u8;
            o[1] = (p[1].clamp(0.0, 1.0) * a * 255.0 + 0.5) as u8;
            o[2] = (p[2].clamp(0.0, 1.0) * a * 255.0 + 0.5) as u8;
            o[3] = (a * 255.0 + 0.5) as u8;
        }
    }
    fn rgba16f(src: &[[f32; 4]], dst: &mut [u8]) {
        for (o, p) in dst.as_chunks_mut::<8>().0.iter_mut().zip(src) {
            let a = if p[3].is_nan() { 0.0 } else { p[3].clamp(0.0, 1.0) };
            let [r, g, b, a] = [p[0].max(0.0) * a, p[1].max(0.0) * a, p[2].max(0.0) * a, a].map(|v| f32_to_f16(v).to_le_bytes());
            *o = [r[0], r[1], g[0], g[1], b[0], b[1], a[0], a[1]];
        }
    }
    let bpp = texel_bytes(format) as usize;
    let convert = if format == FORMAT_HIGH { rgba16f } else { rgba8 };
    out.clear();
    out.resize(px.len() * bpp, 0);
    #[cfg(not(target_arch = "wasm32"))]
    if px.len() > 1 << 18 {
        let threads = std::thread::available_parallelism().map_or(4, |n| n.get()).min(16);
        let chunk = px.len().div_ceil(threads);
        std::thread::scope(|s| {
            for (src, dst) in px.chunks(chunk).zip(out.chunks_mut(chunk * bpp)) {
                s.spawn(move || convert(src, dst));
            }
        });
        return;
    }
    convert(px, out);
}

/// IEEE 754 binary32 → binary16, round to nearest even; overflow saturates to the largest
/// finite half (65504) so HDR values never become infinite, NaN becomes 0. Branch-light: the
/// rounding is done with integer adds on the f32 bits (and an f32 add for subnormals).
fn f32_to_f16(v: f32) -> u16 {
    // 2^-14: the smallest normal half; below it the result is subnormal (or zero).
    const MIN_NORMAL: u32 = 113 << 23;
    // 2^16: halves overflow from here (65520 and up round to infinity; saturate instead).
    const OVERFLOW: u32 = 143 << 23;
    // Adding 0.5 (as f32) shifts a subnormal half's bits to the bottom of the mantissa.
    const DENORM_MAGIC: u32 = 126 << 23;
    let bits = v.to_bits();
    let sign = ((bits >> 16) & 0x8000) as u16;
    let a = bits & 0x7fff_ffff;
    if a > 0x7f80_0000 {
        return 0;
    }
    let h = if a >= OVERFLOW {
        0x7bff
    } else if a < MIN_NORMAL {
        (f32::from_bits(a) + f32::from_bits(DENORM_MAGIC)).to_bits().wrapping_sub(DENORM_MAGIC) as u16
    } else {
        // Rebias the exponent and round the 13 dropped mantissa bits to nearest even.
        let odd = (a >> 13) & 1;
        (((a.wrapping_add(0xc800_0fff).wrapping_add(odd)) >> 13).min(0x7bff)) as u16
    };
    sign | h
}

/// IEEE 754 binary16 → binary32.
#[cfg(not(target_arch = "wasm32"))]
fn f16_to_f32(h: u16) -> f32 {
    let sign = if h & 0x8000 != 0 { -1.0 } else { 1.0 };
    let exp = i32::from((h >> 10) & 0x1f);
    let man = f32::from(h & 0x3ff);
    sign * match exp {
        0 => man * 2f32.powi(-24),
        0x1f => {
            if man == 0.0 {
                f32::INFINITY
            } else {
                f32::NAN
            }
        }
        e => (1.0 + man / 1024.0) * 2f32.powi(e - 15),
    }
}

/// One stored texel of `format` as f32 RGBA.
#[cfg(not(target_arch = "wasm32"))]
fn texel_to_f32(format: wgpu::TextureFormat, b: &[u8]) -> [f32; 4] {
    let mut o = [0.0f32; 4];
    for (i, v) in o.iter_mut().enumerate() {
        *v = if format == FORMAT_HIGH {
            f16_to_f32(u16::from_le_bytes([b.get(i * 2).copied().unwrap_or(0), b.get(i * 2 + 1).copied().unwrap_or(0)]))
        } else {
            f32::from(b.get(i).copied().unwrap_or(0)) / 255.0
        };
    }
    o
}

